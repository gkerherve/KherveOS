def get_peak_value(peak_params_grid, peak_name, param_name):
    # Values come back in the grid's own units. The Voigt callers convert
    # sigma (/2.355) and gamma (/2) themselves when they build the lmfit
    # bounds, so no conversion here. (A conversion keyed on the model used to
    # sit below, reading the model from column 12 - that is 'Split', so it
    # never ran; had it run, those bounds would have been divided twice.)
    for i in range(peak_params_grid.GetNumberRows()):
        if peak_params_grid.GetCellValue(i, 0) == peak_name:
            if param_name == 'center':
                return float(peak_params_grid.GetCellValue(i, 2))
            elif param_name == 'height':
                return float(peak_params_grid.GetCellValue(i, 3))
            elif param_name == 'fwhm':
                return float(peak_params_grid.GetCellValue(i, 4))
            elif param_name == 'lg_ratio':
                return float(peak_params_grid.GetCellValue(i, 5))
            elif param_name == 'area':
                return float(peak_params_grid.GetCellValue(i, 6))
            elif param_name == 'sigma':
                return float(peak_params_grid.GetCellValue(i, 7))
            elif param_name == 'gamma':
                return float(peak_params_grid.GetCellValue(i, 8))
            elif param_name == 'fwhm_g':
                return float(peak_params_grid.GetCellValue(i, 9))
            elif param_name == 'skew':
                return float(peak_params_grid.GetCellValue(i, 9))

    return None



def calculate_weights(window, y_values_filtered, y_values_subtracted):
    """Calculate weights based on the selected method in the fitting window"""
    try:
        weights_method = window.fitting_window.get_weights_method() if window.fitting_window else "uniform"
    except:
        weights_method = "uniform"

    # Counting noise is set by everything the detector recorded, background
    # included: sigma_i ~ sqrt(raw y_i). Weighting by the background-
    # subtracted signal gave the tails and baseline (y - bkg ~ 0, clipped to
    # 1) the largest weight, so the fit followed the noise in the tails.
    if weights_method == "statistical-XPS":
        weights = 1.0 / np.sqrt(np.maximum(y_values_filtered, 1))
    elif weights_method == "hybrid-XPS":
        # Statistical, with a low weight for very low counts
        weights = np.where(y_values_filtered > 10,
                           1.0 / np.sqrt(np.maximum(y_values_filtered, 10)), 0.1)
        weights = weights / np.max(weights)

    elif weights_method == "intensity-based":
        # Statistical weighting for XPS data
        weights = np.sqrt(np.maximum(y_values_subtracted, 0.1))
        weights = weights / np.max(weights)

    else:
        # Uniform weighting (default)
        weights = np.ones(len(y_values_filtered))

    return weights

def relax_intensity_ceiling(vmax, data_ceiling):
    """Raise the default upper limit 1e7 of Height/Area to ``data_ceiling``
    when the data need more. Any other upper limit is the user's and is kept."""
    try:
        if float(vmax) == 1e7 and data_ceiling > 1e7:
            return data_ceiling
    except (TypeError, ValueError):
        pass
    return vmax


def relax_intensity_floor(vmin, vmax):
    """The old default Height/Area constraint '1:1e7' put a floor of 1 under
    every peak, so any area below 1 (normalised data, small CPS) was pushed up
    to 1 before the fit started. New peaks now get '0:1e7'; this lets projects
    saved with the old default fit small peaks too. Other bounds are kept."""
    try:
        if float(vmin) == 1.0 and float(vmax) >= 1e6:
            return 0.0
    except (TypeError, ValueError):
        pass
    return vmin


def safe_bounds(vmin, vmax, pad=1e-4):
    """lmfit rejects parameters with min == max; widen degenerate bounds.

    Linked constraints such as "A*1" can resolve to identical numeric bounds
    (e.g. when the referenced cell holds 0 or cannot be read), so every
    params.add() using evaluated constraints should pass through this guard.
    """
    try:
        lo, hi = float(vmin), float(vmax)
    except (TypeError, ValueError):
        return vmin, vmax
    if lo > hi:
        lo, hi = hi, lo
    if lo == hi:
        pad = max(pad, abs(lo) * 1e-3)
        return lo - pad, hi + pad
    return lo, hi


def _link_bounds(ref, operator, value, delta):
    """(min, max) strings for a link 'ref op value' with tolerance delta.
    For '-' and '/' a larger number gives a smaller result, so the ends
    are swapped to keep min <= max."""
    lo, hi = value - delta, value + delta
    if operator in ('-', '/'):
        lo, hi = hi, lo
    return f"{ref}{operator}{lo}", f"{ref}{operator}{hi}"


