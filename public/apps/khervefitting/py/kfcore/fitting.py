def calculate_r2(y_true, y_pred):
    """Calculate the coefficient of determination (R²)"""
    ss_res = np.sum((y_true - y_pred) ** 2)
    ss_tot = np.sum((y_true - np.mean(y_true)) ** 2)
    return 1 - (ss_res / ss_tot)


def calculate_chi_square(y_true, y_pred):
    """Calculate the chi-square value"""
    return np.sum((y_true - y_pred) ** 2 / y_pred)


def _offset_term_function(basis):
    """c * basis on the fitted range: a Adv. Fitting offset term (lmfit
    reads the parameters from the signature, so basis is closed over)."""
    def offset_term(x, c):
        return c * basis
    return offset_term


