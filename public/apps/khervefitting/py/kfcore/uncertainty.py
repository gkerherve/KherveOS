_REPORT_QTYS = ('Position', 'FWHM', 'Area', 'Height', 'L/G')


def _report_value(qty, v):
    """A value for the report table: readable even for areas of 1e10."""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return str(v)
    if qty in ('Height', 'Area'):
        return f"{f:.4g}" if abs(f) >= 1e6 else format_intensity(f)
    return f"{f:.2f}"


def _report_err(e):
    if e is None:
        return ''
    try:
        f = float(e)
    except (TypeError, ValueError):
        return str(e)
    return f"{f:.2g}" if abs(f) >= 1e6 else fmt_err(f)


def _report_rows(window, sheet):
    """Rows: peak, then for each quantity value / ± covariance / ± Monte Carlo,
    then notes. Returns (rows, covariance method text, Monte Carlo method text)."""
    peaks = (window.Data['Core levels'].get(sheet, {}).get('Fitting', {}).get('Peaks', {}))
    rows, method, mc_method = [], '', ''
    for label, peak in peaks.items():
        errors = peak.get('Errors') or {}
        mc = peak.get('Errors_MC') or {}
        method = errors.get('method', method)
        mc_method = mc.get('method', mc_method)
        status = errors.get('status', {})
        cells = [label]
        notes = []
        for qty in _REPORT_QTYS:
            cells.append(_report_value(qty, peak.get(qty, '')))
            st = status.get(qty)
            if st == 'fixed':
                cells += ['fixed', 'fixed']
            else:
                cells.append(_report_err(errors.get(qty)))
                cells.append(_report_err(mc.get(qty)))
            if st and st != 'fixed':
                notes.append(f"{qty} {st}")
        cells.append('; '.join(notes))
        rows.append(cells)
    return rows, method, mc_method


