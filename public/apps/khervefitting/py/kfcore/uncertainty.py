"""
Uncertainties of fitted peak parameters, and the peak links they depend on.

Three pieces, used by Functions.fit_peaks and the Fitting window:

1. ``apply_peak_links`` - a constraint such as ``A*0.5`` or ``A+1.5#0.2`` on a
   peak's Position, Area, FWHM, Height or L/G used to be turned into narrow
   numeric bounds, computed from peak A's value *before* the fit. The linked
   parameter then sat pinned on those bounds: it did not follow A during the
   fit, and its uncertainty came out as ~0. Here the link becomes a real lmfit
   expression, ``target = A op k``, with ``k`` allowed the same range as before
   (``value +/- tolerance``), so the fitted doublet partner follows A exactly
   and inherits A's uncertainty.

2. ``covariance_errors`` - 1-sigma errors from the fit's covariance matrix
   (lmfit scales it by the reduced chi-square, scale_covar=True). Position,
   Height, FWHM, L/G and Area are pushed through the SAME formulas that fill
   the peak grid (``peak_quantities``), by a numerical Jacobian, so derived
   values (Voigt FWHM and height, DS area, ...) and linked peaks get correct
   errors.

3. ``monte_carlo_errors`` - refits the spectrum many times with the residuals
   resampled onto the best fit (a weighted residual bootstrap). Slower, but
   does not assume the errors are small and linear, which matters for
   strongly overlapping peaks. The background is held fixed. Works on the
   last fit, or on a peak table that was never fitted (``_reference_fit``).
   The results window adds the correlation matrix and scatter plots; the
   full method is the Uncertainties page of the User Guide (the "How does
   it work?" button opens it).

Errors are stored on each peak as ``peak['Errors']``::

    {'method': 'covariance' | 'monte carlo (N)',
     'Position': 0.012, 'Area': 35.1, 'FWHM': 0.02, 'Height': 12.0, 'L/G': 1.4,
     'status': {'Area': 'linked to A', 'FWHM': 'fixed', ...}}

A quantity whose error cannot be given is left out; its status says why.
"""

import re
import numpy as np

from .numberformat import format_intensity
from .peak_functions import PeakFunctions

QUANTITIES = ('Position', 'Height', 'FWHM', 'L/G', 'Area')

# ---------------------------------------------------------------------------
# 1. Peak links -> lmfit expressions
# ---------------------------------------------------------------------------

# Models whose lmfit 'amplitude' IS the peak area (others use 'area', or an
# amplitude that is not an area: DS, and the Height models).
_AMPLITUDE_IS_AREA = {
    "ExpGauss.(Area, σ, γ)", "LA (Area, σ, γ)", "LF (Area, σ, γ, w)",
    "DL (A, σ, γ, aDL)", "TLA (A, μ, α, Wg)", "DS*G (A, σ, γ, S)",
    "LA (Area, σ/γ, γ)", "LA*G (Area, σ/γ, γ)",
}
_HEIGHT_MODELS = {"GL (Height)", "SGL (Height)", "SB (Height)"}
# Models whose 'fraction' parameter is the grid's L/G value, in the same units
_FRACTION_IS_LG = {
    "GL (Area)", "SGL (Area)", "GL (Height)", "SGL (Height)", "SB (Height)",
    "Voigt (Area)", "Voigt (Area, L/G, S)", "A*GL (Area, a, b)", "A*SGL (Area, a, b)",
    "LA (Area, σ/γ, γ)", "LA*G (Area, σ/γ, γ)",
}

# grid column -> quantity name
_LINK_COLUMNS = {2: 'Position', 3: 'Height', 4: 'FWHM', 5: 'L/G', 6: 'Area'}
# Line-shape columns -> the lmfit parameter they hold (same name in every
# model that has it). Linked only between peaks of the same model. The grid
# may show a scaled value (Voigt: Gaussian FWHM = 2.355 sigma, 2 gamma); the
# scale is read from the peak itself, so no per-model table is needed.
_SHAPE_COLUMNS = {7: ('sigma', 'σ'), 8: ('gamma', 'γ'), 9: ('skew', 'skew')}

# Same tolerances parse_constraints() gives the plain forms, so a link allows
# exactly the range it allowed before - it now follows the fitted reference.
_SIMPLE_TOL_ADD = 0.05
_SIMPLE_TOL_MUL = 0.0001

_LINK_RE = re.compile(r'^([A-Z])([+\-*/])(\d+\.?\d*)(?:#([\d.]+))?$')


def _lmfit_name(params, prefix, model, quantity):
    """The lmfit parameter holding ``quantity`` for this peak, or None when the
    model has no single parameter for it (then the old bounds stay)."""
    def usable(name):
        p = params.get(name)
        return p is not None and p.expr is None
    if quantity == 'Position':
        return f'{prefix}center' if usable(f'{prefix}center') else None
    if quantity == 'Area':
        if usable(f'{prefix}area'):
            return f'{prefix}area'
        if model in _AMPLITUDE_IS_AREA and usable(f'{prefix}amplitude'):
            return f'{prefix}amplitude'
        return None
    if quantity == 'FWHM':
        return f'{prefix}fwhm' if usable(f'{prefix}fwhm') else None
    if quantity == 'Height':
        if model in _HEIGHT_MODELS and usable(f'{prefix}amplitude'):
            return f'{prefix}amplitude'
        return None
    if quantity == 'L/G':
        if model in _FRACTION_IS_LG and usable(f'{prefix}fraction'):
            return f'{prefix}fraction'
        # Voigt (Area, L/G, σ[, S]): L/G itself is the fitted 'lg' (%)
        if usable(f'{prefix}lg'):
            return f'{prefix}lg'
        return None
    return None


def _peak_index_by_id(grid, peak_id):
    for row in range(0, grid.GetNumberRows(), 2):
        if grid.GetCellValue(row, 0) == peak_id:
            return row // 2
    return None


def apply_peak_links(params, grid, num_peaks):
    """Turn in-sheet peak links into lmfit expressions (see module docstring).

    Returns ``{(peak_index, quantity): 'linked to A'}`` for the links made.
    A link that cannot be expressed (different units, a model without that
    parameter, a reference to another core level, a loop A->B->A) keeps the
    bounds parse_constraints() already gave it.
    """
    models = [grid.GetCellValue(i * 2, 13) for i in range(num_peaks)]

    def usable(name):
        p = params.get(name)
        return p is not None and p.expr is None

    wanted = []   # (i, quantity, target, ref_index, ref_name, op, value, tol, exact)
    columns = [(c, q, None) for c, q in _LINK_COLUMNS.items()] + \
              [(c, q, pname) for c, (pname, q) in _SHAPE_COLUMNS.items()]
    for i in range(num_peaks):
        prefix = f'peak{i}_'
        for col, quantity, pname in columns:
            m = _LINK_RE.match(grid.GetCellValue(i * 2 + 1, col).strip())
            if not m:
                continue
            ref_id, op, value, tol = m.groups()
            j = _peak_index_by_id(grid, ref_id)
            if j is None or j == i or j >= num_peaks:
                continue
            # Height, L/G and the line-shape values only between peaks of the
            # same model (units differ)
            if (quantity in ('Height', 'L/G') or pname) and models[i] != models[j]:
                continue
            if pname:
                target, ref = f'{prefix}{pname}', f'peak{j}_{pname}'
                if not (usable(target) and usable(ref)):
                    continue
            else:
                target = _lmfit_name(params, prefix, models[i], quantity)
                ref = _lmfit_name(params, f'peak{j}_', models[j], quantity)
            if target is None or ref is None:
                continue
            value = float(value)
            if tol is not None:
                tol, exact = float(tol), False
            elif op in '+-':
                tol, exact = _SIMPLE_TOL_ADD, False
            else:
                tol, exact = _SIMPLE_TOL_MUL, True
            if op == '/' and value == 0:
                continue
            if pname and op in '+-':
                # An offset typed in grid units -> lmfit units
                try:
                    scale = float(grid.GetCellValue(i * 2, col)) / params[target].value
                except (ValueError, ZeroDivisionError):
                    continue
                if not np.isfinite(scale) or scale <= 0:
                    continue
                value, tol = value / scale, tol / scale
            wanted.append((i, quantity, target, j, ref, op, value, tol, exact))

    # Drop links that would make a loop (A = B*1 and B = A*1)
    depends = {w[2]: w[4] for w in wanted}

    def loops(start):
        seen, cur = set(), start
        while cur in depends:
            if cur in seen:
                return True
            seen.add(cur)
            cur = depends[cur]
        return cur == start

    linked = {}
    for (i, quantity, target, j, ref, op, value, tol, exact) in wanted:
        if loops(target):
            continue
        k_name = f'{target}_link'
        t_val, r_val = params[target].value, params[ref].value
        try:
            k0 = {'+': t_val - r_val, '-': r_val - t_val,
                  '*': t_val / r_val, '/': r_val / t_val}[op]
        except ZeroDivisionError:
            k0 = value
        if not np.isfinite(k0) or exact or not (value - tol <= k0 <= value + tol):
            k0 = value
        # Snap float noise (464.50 - 458.80 = 5.6999999999999886). A bounded
        # parameter just off the middle of its range has an internal value of
        # ~1e-13 in lmfit's arcsin transform, and MINPACK's step, relative to
        # it, is then too small to move it at all: the link would stay frozen.
        if abs(k0 - value) <= 1e-9 * max(1.0, abs(value)):
            k0 = value
        if exact:
            params.add(k_name, value=value, vary=False)
        else:
            params.add(k_name, value=k0, min=value - tol, max=value + tol, vary=True)
        # An expression parameter ignores its own bounds in the fit; clear
        # them so the pre-fit numeric window cannot clip the linked value.
        params[target].set(min=-np.inf, max=np.inf)
        params[target].set(expr=f'{ref} {op} {k_name}')
        linked[(i, quantity)] = f'linked to {_grid_id(grid, j)}'
    return linked


def _grid_id(grid, j):
    return grid.GetCellValue(j * 2, 0) or chr(ord('A') + j)


