def fmt_err(value):
    """An uncertainty with two significant figures ('0.0042', '35', '1200')."""
    if value is None or value == '':
        return ''
    try:
        v = float(value)
    except (TypeError, ValueError):
        return str(value)
    if not np.isfinite(v):
        return ''
    if v == 0:
        return '0'
    digits = max(0, 1 - int(np.floor(np.log10(abs(v)))))
    return f"{v:.{min(digits, 8)}f}"


def result_error_fields(peak):
    """Results-row keys for one fitted peak dict (its 'Errors' entry)."""
    peak = peak or {}
