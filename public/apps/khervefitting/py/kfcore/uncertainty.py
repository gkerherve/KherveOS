# 3. Monte Carlo (residual bootstrap)
# ---------------------------------------------------------------------------

def monte_carlo_errors(result, peaks, x, n_runs=100, progress=None, seed=None, stats=None):
    """Refit ``n_runs`` synthetic spectra (best fit + resampled residuals).

    Weighted residual bootstrap: with fit weights w_i (e.g. 1/sqrt(counts)
    for statistical weighting) the residuals are first standardised,
    e_i = w_i (y_i - f_i), resampled with replacement, and put back at each
    point on that point's own scale, y*_i = f_i + e*_i / w_i. So the noise
    on a peak top stays larger than on the baseline, as in the measurement.
    With uniform weights this is the plain residual bootstrap.

    ``progress(k, n)`` is called after each run; returning False stops early.
    ``stats``, a dict, receives per-quantity 'mean', 'p16', 'p84', the
    'reference' values, every refit's values ('runs', for the correlation
    matrix and scatter plots) and the number of 'failed' refits.
    Returns ({(i, quantity): std}, runs_done).
    """
    rng = np.random.default_rng(seed)
    y = np.asarray(result.data, dtype=float)
    best = np.asarray(result.best_fit, dtype=float)
    weights = getattr(result, 'weights', None)
    w = np.ones_like(best) if weights is None else np.asarray(weights, dtype=float)
    if w.shape != best.shape:
        w = np.ones_like(best)
    ok = np.isfinite(y) & np.isfinite(best) & np.isfinite(w) & (w > 0)
    std_resid = ((y - best) * w)[ok]
    if std_resid.size < 3:
        return {}, 0
    w_safe = np.where(ok, w, 1.0)
    kws = dict(getattr(result, 'userkws', {}) or {})
    reference = all_quantities(result.params, peaks, x)
    samples = {}
    runs = []   # one {(i, quantity): value} per successful refit
    done = failed = 0
    for k in range(n_runs):
        y_sim = best + rng.choice(std_resid, size=best.size, replace=True) / w_safe
        try:
            r = result.model.fit(y_sim, result.params.copy(), weights=weights,
                                 method='leastsq', nan_policy='omit',
                                 max_nfev=2000, **kws)
            q = all_quantities(r.params, peaks, x)
            for key, v in q.items():
                samples.setdefault(key, []).append(v)
            runs.append(q)
            done += 1
        except Exception:
            failed += 1
        if progress is not None and progress(k + 1, n_runs) is False:
            break
    errors = {key: float(np.std(v, ddof=1)) for key, v in samples.items() if len(v) >= 3}
    if stats is not None:
        stats['failed'] = failed
        stats['reference'] = reference
        stats['runs'] = runs
        for key, v in samples.items():
            if len(v) >= 3:
                a = np.asarray(v)
                stats.setdefault('mean', {})[key] = float(a.mean())
                stats.setdefault('p16', {})[key] = float(np.percentile(a, 15.87))
                stats.setdefault('p84', {})[key] = float(np.percentile(a, 84.13))
    return errors, done


