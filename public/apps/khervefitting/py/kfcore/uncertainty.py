# 2. Peak quantities from a parameter set (the formulas of the peak grid)
# ---------------------------------------------------------------------------

def peak_quantities(model, pv, prefix, x=None):
    """Position / Height / FWHM / L/G / Area of one peak from parameter values.

    ``pv(name)`` returns a parameter value. Mirrors the conversions in
    Functions.fit_peaks that fill the peak grid (L/G in %); quantities that
    are only found numerically there (maximum over the data points) are left
    out, as their derivative is not meaningful.
    """
    P = PeakFunctions
    q = {}
    try:
        q['Position'] = pv(f'{prefix}center')
    except KeyError:
        return q

    def g(name):
        return pv(f'{prefix}{name}')

    try:
        if model in ("Voigt (Area, L/G, σ)", "Voigt (Area, σ, γ)"):
            a, s, gm = g('amplitude'), g('sigma'), g('gamma')
            q['Area'] = a
            q['Height'] = P.get_voigt_height(a, s, gm)
            q['FWHM'] = P.voigt_fwhm(s, gm)
            q['L/G'] = (2 * gm) / (s * 2.355 + 2 * gm) * 100
        elif model == "Voigt (Area, L/G, σ, S)":
            a, s, gm, sk = g('amplitude'), g('sigma'), g('gamma'), g('skew')
            q['Area'] = a
            q['Height'] = P.get_skewedvoigt_height(a, s, gm, sk)
            q['FWHM'] = P.skewed_voigt_fwhm(s, gm, sk)
            q['L/G'] = (2 * gm) / (s * 2.355 + 2 * gm) * 100
        elif model == "DS (A, σ, γ)":
            import lmfit
            a, c, s, gm, asym = g('amplitude'), g('center'), g('sigma'), g('gamma'), g('asymmetry')
            h = float(lmfit.models.DoniachModel().eval(
                x=np.array([c]), amplitude=a, center=c, sigma=s, gamma=gm, asymmetry=asym)[0])
            q['Height'] = h
            q['Area'] = P.doniach_sunjic_height_to_area(h, s, gm, asym)
            q['FWHM'] = 2 * s
        elif model == "Pseudo-Voigt (Area)":
            a, s, f = g('area'), g('sigma'), g('fraction') * 100
            q['Area'] = a
            q['FWHM'] = 2 * s
            q['L/G'] = f
            q['Height'] = P.get_pseudo_voigt_height(a, s, f)
        elif model in ("GL (Area)",):
            a, w, f = g('area'), g('fwhm'), g('fraction')
            q.update(Area=a, FWHM=w, **{'L/G': f})
            q['Height'] = a / (w * np.sqrt(np.pi / (4 * np.log(2))))
        elif model == "SGL (Area)":
            a, w, f = g('area'), g('fwhm'), g('fraction')
            q.update(Area=a, FWHM=w, **{'L/G': f})
            sig, gam = w / (2 * np.sqrt(2 * np.log(2))), w / 2
            q['Height'] = a / ((1 - f / 100) * sig * np.sqrt(2 * np.pi) + (f / 100) * np.pi * gam)
        elif model in ("GL (Height)", "SGL (Height)"):
            h, w, f = g('amplitude'), g('fwhm'), g('fraction')
            q.update(Height=h, FWHM=w, **{'L/G': f})
            q['Area'] = h * w * np.sqrt(np.pi / (4 * np.log(2)))
        elif model == "Voigt (Area)":
            a, w, f = g('area'), g('fwhm'), g('fraction')
            q.update(Area=a, FWHM=w, **{'L/G': f})
            c = q['Position']
            q['Height'] = float(P.voigt_simple(c, c, a, w, f))
        elif model == "Voigt (Area, L/G, S)":
            a, w, f, sk = g('area'), g('fwhm'), g('fraction'), g('skew')
            q.update(Area=a, FWHM=w, **{'L/G': f})
            c = q['Position']
            q['Height'] = float(P.voigt_simple_skewed(c, c, a, w, f, sk))
        elif model == "A*GL (Area, a, b)":
            a, w, f = g('area'), g('fwhm'), g('fraction')
            q.update(Area=a, FWHM=w, **{'L/G': f})
            q['Height'] = P.A_GL_area_to_height(a, w, f, g('a'), g('b'))
        elif model == "A*SGL (Area, a, b)":
            a, w, f = g('area'), g('fwhm'), g('fraction')
            q.update(Area=a, FWHM=w, **{'L/G': f})
            q['Height'] = P.A_SGL_area_to_height(a, w, f, g('a'), g('b'))
        elif model == "SB (Height)":
            q.update(Height=g('amplitude'), FWHM=g('fwhm'), **{'L/G': g('fraction')})
        elif model in _AMPLITUDE_IS_AREA:
            q['Area'] = g('amplitude')
            if f'{prefix}fwhm' in _names(pv):
                q['FWHM'] = g('fwhm')
            if model in ("LA (Area, σ/γ, γ)", "LA*G (Area, σ/γ, γ)"):
                q['L/G'] = g('fraction')
    except (KeyError, ValueError, ZeroDivisionError, FloatingPointError):
        pass
    return {k: float(v) for k, v in q.items() if v is not None and np.isfinite(v)}


def _names(pv):
    return getattr(pv, 'names', ())


class _Values:
    """``pv`` for peak_quantities over an lmfit Parameters (expressions
    re-evaluated on access)."""

    def __init__(self, params):
        self.params = params
        self.names = tuple(params.keys())

    def __call__(self, name):
        return self.params[name].value


def all_quantities(params, peaks, x=None):
    """{(i, quantity): value} for every peak. ``peaks`` = [(i, model), ...]."""
    # Re-evaluate every expression in dependency order first. lmfit evaluates
    # an expression lazily from the values its inputs last had, so after one
    # parameter is nudged a chain like amplitude = area = A_area * k (Voigt
    # linked to A) read the old area - the derivative came out 0 and the
    # linked peak's area error was 0.
    try:
        params.update_constraints()
    except Exception:
        pass
    pv = _Values(params)
    out = {}
    for i, model in peaks:
        for k, v in peak_quantities(model, pv, f'peak{i}_', x).items():
            out[(i, k)] = v
    return out


# ---------------------------------------------------------------------------
# Parameter status (why an error is missing or not trustworthy)
# ---------------------------------------------------------------------------

def _status(params, prefix, model, quantity, links):
    name = _lmfit_name_any(params, prefix, model, quantity)
    if name is None:
        return None
    p = params[name]
    if p.expr is not None and not p.expr.startswith(prefix):
        return links or 'linked'
    if not p.vary and p.expr is None:
        return 'fixed'
    # At a bound: closer to it than a small fraction of the value itself (a
    # fraction of the range would flag an area of 997 inside 0:1e7). Only
    # finite bounds count.
    near = max(abs(p.value) * 1e-4, 1e-12)
    for bound in (p.min, p.max):
        if np.isfinite(bound) and abs(p.value - bound) <= near:
            return 'at limit'
    return None


def _lmfit_name_any(params, prefix, model, quantity):
    # Like _lmfit_name, but also for parameters that are already expressions
    for cand in {'Position': ('center',), 'Area': ('area', 'amplitude'),
                 'FWHM': ('fwhm',), 'Height': ('amplitude',),
                 'L/G': ('fraction', 'lg')}.get(quantity, ()):
        if cand == 'amplitude' and quantity == 'Area' and model not in _AMPLITUDE_IS_AREA:
            continue
        if cand == 'amplitude' and quantity == 'Height' and model not in _HEIGHT_MODELS:
            continue
        if f'{prefix}{cand}' in params:
            return f'{prefix}{cand}'
    return None


def statuses(params, peaks, links):
    out = {}
    for i, model in peaks:
        for qty in QUANTITIES:
            st = _status(params, f'peak{i}_', model, qty, links.get((i, qty)))
            if st:
                out[(i, qty)] = st
    return out


