def store_errors(existing_peaks, labels, errors, status, method, key='Errors'):
    """Put the errors on each peak's dict as ``peak[key]``: 'Errors' for the
    covariance estimate made by every fit, 'Errors_MC' for a Monte Carlo run.
    A new fit (key 'Errors') drops the Monte Carlo result of the old one."""
    for i, label in labels:
        peak = existing_peaks.get(label)
        if peak is None:
            continue
        entry = {'method': method}
        st = {}
        for qty in QUANTITIES:
            s = status.get((i, qty))
            if s:
                st[qty] = s
            if s == 'fixed':
                continue
            v = errors.get((i, qty))
            if v is not None and np.isfinite(v):
                entry[qty] = float(v)
                # An error larger than the value: the data do not determine
                # this quantity with this model (overlapping peaks, a bound,
                # a near-singular problem - see the User Guide, Uncertainties).
                if qty in ('Height', 'Area', 'FWHM') and not s:
                    try:
                        value = abs(float(peak.get(qty)))
                    except (TypeError, ValueError):
                        value = None
                    if value is not None and float(v) > value:
                        st[qty] = 'ill-conditioned'
        if st:
            entry['status'] = st
        peak[key] = entry
        if key == 'Errors':
            peak.pop('Errors_MC', None)


def format_pm(value, error):
    """'1234 ± 12' with the value rounded to the error's precision."""
    if error is None or not np.isfinite(error) or error <= 0:
        return None
    digits = max(0, 1 - int(np.floor(np.log10(error))))
    digits = min(digits, 8)
    return f"{value:.{digits}f} ± {error:.{digits}f}"


