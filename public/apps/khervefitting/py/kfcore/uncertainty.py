# 2b. Covariance errors
# ---------------------------------------------------------------------------

def covariance_errors(result, peaks, x=None):
    """{(i, quantity): 1-sigma} from the fit covariance, through a numerical
    Jacobian of peak_quantities. Empty when the fit gave no covariance
    (Nelder-Mead, Powell, COBYLA, or a singular problem)."""
    covar = getattr(result, 'covar', None)
    names = list(getattr(result, 'var_names', None) or [])
    if covar is None and names:
        covar = numeric_covariance(result, names)
    if covar is None or not names:
        return {}
    covar = np.asarray(covar, dtype=float)
    if covar.shape != (len(names), len(names)) or not np.all(np.isfinite(covar)):
        return {}

    params = result.params.copy()
    base = all_quantities(params, peaks, x)
    grads = {k: np.zeros(len(names)) for k in base}
    for j, n in enumerate(names):
        p = params[n]
        v0 = p.value
        sd = np.sqrt(covar[j, j]) if covar[j, j] > 0 else 0.0
        h = max(sd * 1e-2, abs(v0) * 1e-7, 1e-12)
        p.value = v0 + h
        v_up = p.value
        up = all_quantities(params, peaks, x)
        p.value = v0 - h
        v_dn = p.value
        dn = all_quantities(params, peaks, x)
        p.value = v0
        step = v_up - v_dn
        if step == 0:
            continue
        for k in base:
            if k in up and k in dn:
                grads[k][j] = (up[k] - dn[k]) / step
    errors = {}
    for k, gvec in grads.items():
        var = float(gvec @ covar @ gvec)
        if var >= 0 and np.isfinite(var):
            errors[k] = np.sqrt(var)
    return errors


def numeric_covariance(result, names):
    """Covariance of the varied parameters at the best fit, from a numerical
    Jacobian of the weighted residual: inv(J^T J) * reduced chi-square - what
    lmfit reports with scale_covar=True.

    Needed because MINPACK's leastsq often returns no covariance when it
    starts at (or very near) the minimum - which is every refit the app does
    from the grid's converged values - and because Nelder-Mead, Powell and
    COBYLA never return one.
    """
    try:
        model, data = result.model, np.asarray(result.data, dtype=float)
        kws = dict(getattr(result, 'userkws', {}) or {})
        weights = getattr(result, 'weights', None)
        params = result.params.copy()

        def resid():
            r = model.eval(params, **kws) - data
            if weights is not None:
                r = r * weights
            return np.asarray(r, dtype=float)

        base = resid()
        ok = np.isfinite(base)
        J = np.zeros((int(ok.sum()), len(names)))
        for j, n in enumerate(names):
            p = params[n]
            v0 = p.value
            h = max(abs(v0) * 1e-6, 1e-9)
            p.value = v0 + h
            v_up = p.value
            up = resid()
            p.value = v0 - h
            v_dn = p.value
            dn = resid()
            p.value = v0
            if v_up == v_dn:
                return None
            J[:, j] = (up[ok] - dn[ok]) / (v_up - v_dn)
        nfree = ok.sum() - len(names)
        if nfree <= 0:
            return None
        redchi = float(np.sum(base[ok] ** 2)) / nfree
        cov = np.linalg.inv(J.T @ J) * redchi
        if not np.all(np.isfinite(cov)) or np.any(np.diag(cov) < 0):
            return None
        return cov
    except (np.linalg.LinAlgError, AttributeError, TypeError, ValueError):
        return None


