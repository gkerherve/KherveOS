_ALLOWED_MODELS_EXCLUDED = ("D-parameter", "Unfitted", "Fermi", "")


def _reference_fit(window, parent):
    """The lmfit result Monte Carlo starts from: the last fit of this sheet,
    or - for a peak table that has not been fitted in this session - the
    model evaluated at the table's values (the table is not changed).
    Returns (fit_results, 'fit' | 'table') or (None, message)."""
    sheet = window.sheet_combobox.GetValue()
    fr = getattr(window, 'fit_results', None) or {}
    result = fr.get('result')
    if (result is not None and hasattr(result, 'model') and fr.get('sheet_name') == sheet
            and not getattr(result, 'evaluated_only', False)):
        return fr, 'fit'
    grid = getattr(window, 'peak_params_grid', None)
    if grid is None or grid.GetNumberRows() < 2:
        return None, "This core level has no peaks. Add peaks to the table first."
    if grid.GetCellValue(0, 13) in _ALLOWED_MODELS_EXCLUDED:
        return None, "Monte Carlo needs a fitted line shape (not D-parameter / Fermi / Unfitted)."
    # Evaluating the table rebuilds the peak dicts' covariance entry: keep
    # the errors a saved fit may carry.
    peaks = (window.Data.get('Core levels', {}).get(sheet, {})
             .get('Fitting', {}).get('Peaks', {}))
    kept = {k: v.get('Errors') for k, v in peaks.items() if v.get('Errors')}
    try:
        from .fitting import fit_peaks
        fit_peaks(window, grid, evaluate=True)
    except Exception as e:
        return None, f"Could not build the model from the peak table:\n{e}"
    for k, err in kept.items():
        if k in peaks:
            peaks[k]['Errors'] = err
    fr = getattr(window, 'fit_results', None) or {}
    if fr.get('sheet_name') != sheet or not hasattr(fr.get('result'), 'model'):
        return None, "Could not build the model from the peak table."
    return fr, 'table'


def mc_correlation(stats):
    """(keys, matrix) of Pearson correlations between every quantity that
    varied in all the refits. Fixed or exactly-linked values (zero spread)
    are left out."""
    runs = stats.get('runs') or []
    if len(runs) < 3:
        return [], np.zeros((0, 0))
    keys = [k for k in runs[0] if all(k in r for r in runs)]
    data = np.array([[r[k] for k in keys] for r in runs], dtype=float)
    sd = data.std(axis=0)
    keep = [j for j, v in enumerate(sd) if v > 1e-12 * max(1.0, abs(data[:, j].mean()))]
    keys = [keys[j] for j in keep]
    if len(keys) < 2:
        return keys, np.ones((len(keys), len(keys)))
    corr = np.corrcoef(data[:, keep], rowvar=False)
    # Order by peak, then Position / FWHM / Area / Height / L/G
    order = sorted(range(len(keys)),
                   key=lambda j: (keys[j][0], _REPORT_QTYS.index(keys[j][1])
                                  if keys[j][1] in _REPORT_QTYS else 9))
    keys = [keys[j] for j in order]
    return keys, corr[np.ix_(order, order)]


def _mc_key_name(stats, key):
    i, q = key
    return f"{stats.get('names', {}).get(i, i)} {q}"


def mc_summary_rows(stats):
    """Rows: peak, quantity, reference, MC mean, ±1σ, 16 %, 84 %, shift/σ."""
    rows = []
    ref, mean = stats.get('reference', {}), stats.get('mean', {})
    p16, p84, err = stats.get('p16', {}), stats.get('p84', {}), stats.get('errors', {})
    st = stats.get('status', {})
    for key in sorted(ref, key=lambda k: (k[0], _REPORT_QTYS.index(k[1]) if k[1] in _REPORT_QTYS else 9)):
        i, q = key
        name = stats.get('names', {}).get(i, i)
        if st.get(key) == 'fixed':
            rows.append([name, q, _report_value(q, ref[key]), '', 'fixed', '', '', '', 'fixed'])
            continue
        e = err.get(key)
        shift = ((mean[key] - ref[key]) / e) if e and key in mean else None
        rows.append([name, q, _report_value(q, ref[key]),
                     _report_value(q, mean[key]) if key in mean else '',
                     _report_err(e),
                     _report_value(q, p16[key]) if key in p16 else '',
                     _report_value(q, p84[key]) if key in p84 else '',
                     f"{shift:+.2f}" if shift is not None else '',
                     st.get(key, '')])
    return rows


def uncertainty_summary(window, sheet):
    """Plain-text table of every peak's value ± uncertainty on a sheet."""
    peaks = (window.Data['Core levels'].get(sheet, {}).get('Fitting', {}).get('Peaks', {}))
    lines = []
    method = ''
    for label, peak in peaks.items():
        errors = peak.get('Errors_MC') or peak.get('Errors') or {}
        method = errors.get('method', method)
        status = (peak.get('Errors') or {}).get('status', {})
        parts = []
        for qty in ('Position', 'FWHM', 'Area', 'Height', 'L/G'):
            if qty not in peak:
                continue
            if status.get(qty) == 'fixed':
                parts.append(f"{qty} {peak[qty]} (fixed)")
            elif qty in errors:
                parts.append(f"{qty} {peak[qty]} ± {fmt_err(errors[qty])}")
        if parts:
            lines.append(f"{label}:\n    " + "\n    ".join(parts))
    if not lines:
        return "No uncertainties available for this core level yet."
    head = {'covariance': "1σ from the covariance matrix (scaled by reduced χ²)"}.get(
        method, f"1σ, {method}")
    return head + "\n\n" + "\n".join(lines) + (
        "\n\nHover a value in the peak table to see its uncertainty; the Results\n"
        "table has ± columns (filled when a peak is added to the results).")


