def atomic_percent_errors(window, results_table_key, checked, total):
    """Fit_Uncertainty.atomic_percent_errors on the results table data.

    ``checked`` = [(label, normalised area), ...] of the ticked rows. Each
    row's area error ('Area Err', from the fit) is taken as independent and
    pushed through at% = n_i / sum(n); the area is the results grid's text
    (format_intensity), the error the grid's text (fmt_err), as on the
    desktop. Sets 'at. % Err' on every row ('' when it cannot be given).
    """
    peaks = window.Data.get(results_table_key, {}).get('Peak', {})
    if total <= 0:
        return
    rel = {}
    for label, n in checked:
        p = peaks.get(label, {})
        try:
            area = float(format_intensity(p.get('Area', '')))
            err = float(fmt_err(p.get('Area Err', '')))
            rel[label] = (n * err / area) if area else None
        except (TypeError, ValueError):
            rel[label] = None
    ticked = {label for label, _n in checked}
    for label, n in checked:
        if rel.get(label) is None:
            value = ''
        else:
            var = ((total - n) / total ** 2) ** 2 * rel[label] ** 2
            for j, _nj in checked:
                if j != label and rel.get(j) is not None:
                    var += (n / total ** 2) ** 2 * rel[j] ** 2
            value = 100.0 * float(np.sqrt(var))
        peaks[label]['at. % Err'] = value
    for label, p in peaks.items():
        if label not in ticked:
            p['at. % Err'] = ''
