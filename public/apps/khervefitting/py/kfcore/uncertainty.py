def errors_by_peak(window, sheet=None):
    """{peak index: {'Position': err, 'Height': err, 'FWHM': err, 'L/G': err,
    'Area': err, 'method': ..., 'status': {...}, 'mc': {...}}} for the current
    peak table, from peak['Errors'] (covariance, every fit) and
    peak['Errors_MC'] (Monte Carlo). Quantities without an error are absent."""
    sheet = sheet or window.sheet_combobox.GetValue()
    grid = window.peak_params_grid
    out = {}
    for row in range(0, grid.GetNumberRows(), 2):
        peak = fitted_peak_for(window, sheet, grid.GetCellValue(row, 1), row // 2) or {}
        errors = peak.get('Errors') or {}
        mc = peak.get('Errors_MC') or {}
        if not errors and not mc:
            continue
        entry = {q: float(errors[q]) for q in QUANTITIES if q in errors}
        entry['method'] = errors.get('method', '')
        if errors.get('status'):
            entry['status'] = dict(errors['status'])
        if mc:
            entry['mc'] = {q: float(mc[q]) for q in QUANTITIES if q in mc}
            entry['mcMethod'] = mc.get('method', '')
        out[row // 2] = entry
    return out


