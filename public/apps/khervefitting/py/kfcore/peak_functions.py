    @staticmethod
    # @jit(nopython=True, parallel=True)
    def LA(x, center, amplitude, fwhm, sigma, gamma):
        #amplitude here is the area

        # Calculate lorentzian width from the input FWHM
        F = 2 * fwhm / (np.sqrt(2 ** (1 / sigma) - 1) + np.sqrt(2 ** (1 / gamma) - 1))

        # Create the peak shape with unit amplitude
        peak_shape = np.where(
            x <= center,
            1 / (1 + 4 * ((x - center) / F) ** 2) ** gamma,
            1 / (1 + 4 * ((x - center) / F) ** 2) ** sigma
        )

        # Sort x values and corresponding peak shape for correct integration
        sort_idx = np.argsort(x)
        x_sorted = x[sort_idx]
        peak_shape_sorted = peak_shape[sort_idx]

        # Calculate the area of unit amplitude peak
        unit_area = abs(trapz(peak_shape_sorted, x_sorted))

        # Calculate required amplitude to achieve desired area
        height = amplitude / unit_area if unit_area != 0 else 0

        return height * peak_shape

    @staticmethod
    def LF(x, center, amplitude, fwhm, sigma, gamma, w=30.0):
        """LF (finite Lorentzian): LA with exponents that grow with distance.

        Exact form from Major, Shah, Avval, Fernandez, Fairley & Linford,
        "Advanced Line Shapes in XPS II. The Finite Lorentzian (LF) Line Shape",
        Vacuum Technology & Coating, April 2020 (MATLAB listing):
            exp_eff(t) = 3 - (3 - exp0) / (1 + 4*(t/w)^2)
        i.e. the LA exponents ramp smoothly (Lorentzian-shaped ramp of width w)
        from their entered values at the peak to the constant 3 far away, which
        drives the tails to the baseline and makes the area finite.
        w ranges ~1 (strongest suppression) to 1000 (essentially LA).
        amplitude is the peak area (numerically normalised like LA).
        """
        # Calculate lorentzian width from the input FWHM
        F = 2 * fwhm / (np.sqrt(2 ** (1 / sigma) - 1) + np.sqrt(2 ** (1 / gamma) - 1))

        t = x - center
        L = 1 / (1 + 4 * (t / F) ** 2)

        # Exponents ramp from the LA values at the peak to 3 on the scale w
        ASYM_LIMIT = 3.0
        w_safe = max(float(w), 1e-3)
        ramp = 1.0 / (1.0 + 4.0 * (t / w_safe) ** 2)
        expo = np.where(t <= 0, gamma, sigma)  # same side convention as LA
        expo = ASYM_LIMIT - (ASYM_LIMIT - expo) * ramp
        peak_shape = L ** expo

        # Normalise to the requested area over the provided x range
        sort_idx = np.argsort(x)
        unit_area = abs(trapz(peak_shape[sort_idx], x[sort_idx]))
        height = amplitude / unit_area if unit_area != 0 else 0

        return height * peak_shape

    @staticmethod
    def DL(x, center=0.0, amplitude=1.0, sigma=0.4, gamma=1.0, a_dl=1.5):
        """Double Lorentzian (Herrera-Gomez et al., JVST A 41, 043208 (2023)).

        A split Lorentzian - narrow side of width sigma (eV) toward lower BE,
        wide side of width a_dl*sigma toward higher BE - analytically normalised
        to unit area, then convolved with a unit-area Gaussian of FWHM gamma (eV).
        'amplitude' is therefore the exact analytic area of the full profile.
        At a_dl = 1 the DL is exactly a Voigt function.
        The convolution shifts the maximum away from E0 toward the tail; here
        the profile is re-anchored so that 'center' is the true peak maximum.
        Grid mapping: sigma column = sigma, gamma column = Gaussian FWHM,
        skew column = a_dl (>= 1).
        """
        x_arr = np.atleast_1d(np.asarray(x, dtype=float))
        sigma = max(float(sigma), 1e-3)
        gamma = max(float(gamma), 0.0)
        a_dl = max(float(a_dl), 0.01)
        offset = _dl_apex_offset(sigma, a_dl, gamma)
        e0 = center - offset

        widths = sigma * (1.0 + a_dl) + gamma
        t_data = x_arr - e0
        span = max(10.0 * widths, (np.max(np.abs(t_data)) if t_data.size else 0.0) + 5.0 * widths)
        step = max(min(sigma, gamma if gamma > 0 else sigma) / 20.0, span / 4000.0)
        n = int(2 * span / step) + 1
        t = np.linspace(-span, span, n)
        y = _dl_unit_profile(t, sigma, a_dl, gamma)
        out = amplitude * np.interp(t_data, t, y)
        return out if np.ndim(x) else float(out[0])

    @staticmethod
    def TLA(x, center=0.0, amplitude=1.0, fwhm=1.0, mu=20.0, wg=1.0, alpha=1.0):
        """CasaXPS TLA asymmetric line shape (Cookbook 2026, Line shapes section).

        A Lorentzian raised to the power alpha and modulated by the arctangent
        tail factor [pi/2 + atan(2t/F) + pi/mu] (tail toward higher BE),
        convolved with a Gaussian of FWHM wg (eV) and normalised to unit area,
        so 'amplitude' is the area. 'fwhm' is the actual FWHM of the
        unconvolved T profile (the Lorentzian width is derived internally).
        The constant pi/mu sets the floor of the modulation: LARGER mu =
        stronger asymmetry, small mu approaches a symmetric shape.
        The profile is re-anchored so 'center' is the true peak maximum.
        Grid mapping: sigma column = mu, gamma column = alpha, W_g/skew
        column = wg (like LA*G, which also keeps its Gaussian width there).
        """
        x_arr = np.atleast_1d(np.asarray(x, dtype=float))
        fwhm = max(float(fwhm), 1e-3)
        mu = max(float(mu), 1e-3)
        wg = max(float(wg), 0.0)
        alpha = max(float(alpha), 0.05)
        offset = _tla_apex_offset(fwhm, mu, wg, alpha)
        e0 = center - offset

        widths = fwhm + wg
        t_data = x_arr - e0
        span = max(10.0 * widths, (np.max(np.abs(t_data)) if t_data.size else 0.0) + 5.0 * widths)
        step = max(min(fwhm, wg if wg > 0 else fwhm) / 20.0, span / 4000.0)
        n = int(2 * span / step) + 1
        t = np.linspace(-span, span, n)
        y = _tla_unit_profile(t, fwhm, mu, wg, alpha)
        out = amplitude * np.interp(t_data, t, y)
        return out if np.ndim(x) else float(out[0])

    @staticmethod
    def SB_voigt(x, center=0.0, fwhm=1.0, fraction=30.0, amplitude=1.0):
        """Shirley-background component SB(0)V (Fairley et al., JVST A 41, 013204
        (2023), Eq. 7: SB(0)F(x) = integral of F from x to infinity, KE axis).

        The sigmoid response of a true Voigt bell of total FWHM 'fwhm' and L/G
        ratio 'fraction': a step of height 'amplitude' rising toward higher BE,
        centred on 'center'. Used as an optimisable background component under
        a photoelectron peak (e.g. CasaXPS SB(0)LA(...)).
        """
        x_arr = np.atleast_1d(np.asarray(x, dtype=float))
        fwhm = max(float(fwhm), 1e-3)
        t_data = x_arr - center
        span = max(20.0 * fwhm, (np.max(np.abs(t_data)) if t_data.size else 0.0) + 10.0 * fwhm)
        n = 4001
        t = np.linspace(-span, span, n)
        bell = PeakFunctions.voigt_simple(t, 0.0, 1.0, fwhm, fraction)
        cdf = np.cumsum(bell)
        cdf = cdf / cdf[-1]
        out = amplitude * np.interp(t_data, t, cdf)
        return out if np.ndim(x) else float(out[0])

    @staticmethod
    # @jit(nopython=True, parallel=True)
    def LAxG(x, center, amplitude, fwhm, sigma, gamma, fwhm_g):
        # Define the LA function
        # gaussian_fwhm =0.64 # now done through the grid

        # Calculate lorentzian width from the input FWHM
        F = 2 * fwhm / (np.sqrt(2 ** (1 / sigma) - 1) + np.sqrt(2 ** (1 / gamma) - 1))
        def LA_N(x):
            return np.where(
                x <= 0,
                1 / (1 + 4 * ((x ) / F) ** 2) ** gamma,
                1 / (1 + 4 * ((x ) / F) ** 2) ** sigma
            )

        # Define the Gaussian function
        def gaussian(x, fwhm_g):
            return np.exp(-4 * np.log(2) * ((x ) / fwhm_g) ** 2)

        x_range = max(x.max() - x.min(), 4 * fwhm)
        x_high_res = np.linspace(- x_range / 2, + x_range / 2, len(x) * 4)

        la = LA_N(x_high_res)
        gauss = gaussian(x_high_res, fwhm_g)

        convolved = convolve(la, gauss, mode='same') / sum(gauss)

        peak_shape = np.interp(x - center, x_high_res, convolved)

        # Sort x values and corresponding peak shape for correct integration
        sort_idx = np.argsort(x)
        x_sorted = x[sort_idx]
        peak_shape_sorted = peak_shape[sort_idx]

        # Calculate the area of unit amplitude peak
        unit_area = abs(trapz(peak_shape_sorted, x_sorted))

        # Calculate required amplitude to achieve desired area
        height = amplitude / unit_area if unit_area != 0 else 0

        return height * peak_shape


    @staticmethod
    def A_GL(x, center=0.0, amplitude=1.0, fwhm=1.0, fraction=30.0, a=0.2, b=0.4):
        """CasaXPS A(a,b,0)GL(p) - Gelius asymmetric Gaussian/Lorentzian product.

        GL(x) = exp(-4ln2(1-m)t^2/F^2) / (1 + 4m t^2/F^2) with m = fraction/100.
        On the high-BE side (t = x - center > 0) an asymmetric tail is added:
        A(x) = GL(x) + w(a,b)*[AW(x) - GL(x;F,E,0)]
        with AW = exp(-(2*sqrt(ln2)*t / (F + a*2*sqrt(ln2)*t))^2),
        GL(x;F,E,0) = exp(-4ln2*t^2/F^2) (pure Gaussian of FWHM F) and
        w(a,b) = b*(0.7 + 0.3/(a + 0.01)).
        Source: CasaXPS "Peak Fitting in XPS" (Casa Software Ltd, 2006), p.20 -
        the Gelius function; formula given there on the KE axis, mapped here to BE.
        The tail term is zero (value and slope) at the center, so 'center' is the
        true peak maximum and 'amplitude' is the height at the maximum.
        """
        x = np.asarray(x, dtype=float)
        m = np.clip(fraction, 0.0, 100.0) / 100.0
        t = x - center
        gl = np.exp(-4 * np.log(2) * (1 - m) * t ** 2 / fwhm ** 2) / (1 + 4 * m * t ** 2 / fwhm ** 2)
        w = b * (0.7 + 0.3 / (a + 0.01))
        # u = 2*sqrt(ln2)*t so that AW(a=0) equals the pure Gaussian of FWHM F.
        # The width grows linearly with distance on the tail side, so AW decays
        # more slowly than the Gaussian and the added term is a positive tail
        # approaching w*exp(-1/a^2) asymptotically.
        u = 2.0 * np.sqrt(np.log(2.0)) * np.where(t > 0, t, 0.0)
        aw = np.exp(-(u / (fwhm + a * u)) ** 2)
        g0 = np.exp(-(u / fwhm) ** 2)
        tail = np.where(t > 0, w * (aw - g0), 0.0)
        return amplitude * (gl + tail)

    @staticmethod
    def A_SGL(x, center=0.0, amplitude=1.0, fwhm=1.0, fraction=30.0, a=0.2, b=0.4):
        """CasaXPS A(a,b,0)SGL(p) - Gelius asymmetric Gaussian/Lorentzian sum.

        Same construction as A_GL but with the SGL sum form as symmetric base:
        SGL(x) = (1-m)*exp(-4ln2*t^2/F^2) + m/(1 + 4t^2/F^2), m = fraction/100.
        The Gelius tail (see A_GL) is added on the high-BE side.
        """
        x = np.asarray(x, dtype=float)
        m = np.clip(fraction, 0.0, 100.0) / 100.0
        t = x - center
        sgl = ((1 - m) * np.exp(-4 * np.log(2) * t ** 2 / fwhm ** 2)
               + m / (1 + 4 * t ** 2 / fwhm ** 2))
        w = b * (0.7 + 0.3 / (a + 0.01))
        u = 2.0 * np.sqrt(np.log(2.0)) * np.where(t > 0, t, 0.0)
        aw = np.exp(-(u / (fwhm + a * u)) ** 2)
        g0 = np.exp(-(u / fwhm) ** 2)
        tail = np.where(t > 0, w * (aw - g0), 0.0)
        return amplitude * (sgl + tail)

