@lru_cache(maxsize=1024)
def _skewed_voigt_apex_offset(sigma, gamma, skew):
    """Offset between lmfit's skewed_voigt 'center' parameter and the actual
    position of the profile maximum (apex - center).

    lmfit's SkewedVoigt multiplies a Voigt by (1 + erf(skew*(x-center)/(sigma*sqrt(2)))),
    which pushes the apex away from 'center' whenever skew != 0.
    """
    if sigma <= 0 or abs(skew) < 1e-9:
        return 0.0
    span = 4.0 * (sigma + abs(gamma)) * (1.0 + abs(skew))
    x = np.linspace(-span, span, 801)
    y = skewed_voigt(x, amplitude=1.0, center=0.0, sigma=sigma, gamma=gamma, skew=skew)
    i = int(np.argmax(y))
    # Refine around the coarse maximum: finer grid + parabolic interpolation
    step = x[1] - x[0]
    x_fine = np.linspace(x[i] - step, x[i] + step, 41)
    y_fine = skewed_voigt(x_fine, amplitude=1.0, center=0.0, sigma=sigma, gamma=gamma, skew=skew)
    j = int(np.argmax(y_fine))
    if 0 < j < len(x_fine) - 1:
        denom = y_fine[j - 1] - 2.0 * y_fine[j] + y_fine[j + 1]
        if denom < 0:
            fine_step = x_fine[1] - x_fine[0]
            return float(x_fine[j] + 0.5 * fine_step * (y_fine[j - 1] - y_fine[j + 1]) / denom)
    return float(x_fine[j])


def _dl_unit_profile(t, sigma_r, a_dl, sigma_g):
    """Unit-area double Lorentzian evaluated at E0 = 0 on the uniform grid t.

    Split Lorentzian (Herrera-Gomez et al., JVST A 41, 043208 (2023), Eq. 2)
    with the wide side (sigma_l = a_dl * sigma_r) toward higher BE (t > 0),
    numerically convolved with the unit-area Gaussian of FWHM sigma_g (Eq. 3-4).
    """
    sig_l = a_dl * sigma_r
    norm = 1.0 / (np.pi * sig_l / 4.0 + np.pi * sigma_r / 4.0)
    ls = norm * np.where(t > 0,
                         1.0 / (1.0 + t ** 2 / (sig_l / 2.0) ** 2),
                         1.0 / (1.0 + t ** 2 / (sigma_r / 2.0) ** 2))
    step = t[1] - t[0]
    if sigma_g > 2.0 * step:
        half = int(np.ceil(4.0 * sigma_g / step))
        tk = np.arange(-half, half + 1) * step
        kernel = np.exp(-4.0 * np.log(2.0) * tk ** 2 / sigma_g ** 2)
        kernel /= kernel.sum()
        ls = convolve(ls, kernel, mode='same')
    return ls


@lru_cache(maxsize=512)
def _dl_apex_offset(sigma_r, a_dl, sigma_g):
    """Offset between the double Lorentzian's E0 and its actual maximum.

    The Gaussian smearing of the asymmetric split Lorentzian pushes the apex
    from E0 toward the wide (high-BE) side; this returns apex - E0.
    """
    if a_dl == 1.0 or sigma_g <= 0.0:
        return 0.0
    span = 8.0 * (sigma_r * (1.0 + a_dl) + sigma_g)
    t = np.linspace(-span, span, 4001)
    y = _dl_unit_profile(t, sigma_r, a_dl, sigma_g)
    i = int(np.argmax(y))
    if 0 < i < len(t) - 1:
        denom = y[i - 1] - 2.0 * y[i] + y[i + 1]
        if denom < 0:
            step = t[1] - t[0]
            return float(t[i] + 0.5 * step * (y[i - 1] - y[i + 1]) / denom)
    return float(t[i])


@lru_cache(maxsize=512)
def _tla_width_scale(mu, alpha):
    """FWHM of the unconvolved T profile for unit Lorentzian FWHM.

    Used so that the model's fwhm parameter is the actual FWHM of the TLA
    shape (before Gaussian convolution) rather than the raw Lorentzian width.
    """
    t = np.linspace(-40.0, 40.0, 80001)
    lor = (1.0 / (1.0 + 4.0 * t ** 2)) ** alpha
    tail = np.pi / 2.0 + np.arctan(2.0 * t) + np.pi / mu
    y = lor * tail
    half = np.max(y) / 2.0
    idx = np.where(y >= half)[0]
    if len(idx) >= 2:
        return float(t[idx[-1]] - t[idx[0]])
    return 1.0


@lru_cache(maxsize=512)
def _tla_apex_offset(fwhm, mu, wg, alpha):
    """Offset between the TLA profile's nominal centre and its actual maximum.

    The arctangent tail factor (and the Gaussian convolution) push the apex
    toward the high-BE side; this returns apex - E0 for a unit-area TLA.
    """
    span = 10.0 * (fwhm + wg)
    t = np.linspace(-span, span, 4001)
    y = _tla_unit_profile(t, fwhm, mu, wg, alpha)
    i = int(np.argmax(y))
    if 0 < i < len(t) - 1:
        denom = y[i - 1] - 2.0 * y[i] + y[i + 1]
        if denom < 0:
            step = t[1] - t[0]
            return float(t[i] + 0.5 * step * (y[i - 1] - y[i + 1]) / denom)
    return float(t[i])


def _tla_unit_profile(t, fwhm, mu, wg, alpha):
    """Unit-area TLA evaluated at E0 = 0 on the uniform grid t (BE axis).

    CasaXPS Cookbook (2026), Line shapes section:
    T(x: alpha, mu) = [1/(1+4x^2)]^alpha * [pi/2 - atan(2x) + pi/mu]
    convolved with a Gaussian; written there on the KE axis, mirrored here so
    the tail extends toward higher BE (t > 0). 'fwhm' is the actual FWHM of
    the unconvolved T profile (internally rescaled via _tla_width_scale).
    """
    f_lor = fwhm / _tla_width_scale(mu, alpha)
    u = t / f_lor
    lor = (1.0 / (1.0 + 4.0 * u ** 2)) ** alpha
    tail = np.pi / 2.0 + np.arctan(2.0 * u) + np.pi / mu
    y = lor * tail
    step = t[1] - t[0]
    if wg > 2.0 * step:
        half = int(np.ceil(4.0 * wg / step))
        tk = np.arange(-half, half + 1) * step
        kernel = np.exp(-4.0 * np.log(2.0) * tk ** 2 / wg ** 2)
        kernel /= kernel.sum()
        y = convolve(y, kernel, mode='same')
    area = trapz(y, t)
    return y / area if area > 0 else y


class PeakFunctions:

    @staticmethod
    def gaussian_other(x, E, F, m):
        return np.exp(-4 * np.log(2) * ((x - E) / F)**2) * (1 - m / 100)

    @staticmethod
    def gaussian(x, E, F, m):
        return np.exp(-4 * np.log(2) * (1 - m / 100) * ((x - E) / F)**2)

    @staticmethod
    def lorentzian(x, E, F, m):
        return 1 / (1 + 4 * m / 100 * ((x - E) / F)**2)

    @staticmethod
    def gauss_lorentz_OLD(x, center, fwhm, fraction, amplitude):
        return amplitude * (
            PeakFunctions.gaussian(x, center, fwhm, fraction*1) *
            PeakFunctions.lorentzian(x, center, fwhm, fraction*1))

    @staticmethod
    def S_gauss_lorentz(x, center, fwhm, fraction, amplitude):
        return amplitude * (
            (1-fraction/100) * PeakFunctions.gaussian(x, center, fwhm, 0) +
            fraction/100 * PeakFunctions.lorentzian(x, center, fwhm, 100))

    @staticmethod
    def gauss_lorentz(x, center , fwhm, fraction, amplitude):
        peak = amplitude * (
                PeakFunctions.gaussian(x, center, fwhm, fraction * 1) *
                PeakFunctions.lorentzian(x, center, fwhm, fraction * 1))
        return peak


    @staticmethod
    def gauss_lorentz_Area(x, center, area, fwhm, fraction):
        sigma = fwhm / (2 * np.sqrt(2 * np.log(2)))
        height = area / (sigma * np.sqrt(2 * np.pi))
        return height * (
                PeakFunctions.gaussian(x, center, fwhm, fraction * 1) *
                PeakFunctions.lorentzian(x, center, fwhm, fraction * 1))

    @staticmethod
    def S_gauss_lorentz_Area_MISMATCH(x, center, area, fwhm, fraction):
        sigma = fwhm / (2 * np.sqrt(2 * np.log(2)))
        height = area / (sigma * np.sqrt(2 * np.pi))
        Area = height * (
                (1 - fraction / 100) * PeakFunctions.gaussian(x, center, fwhm, 0) +
                fraction / 100 * PeakFunctions.lorentzian(x, center, fwhm, 100))
        # print(f"SGL Area: {Area}")
        return Area

    @staticmethod
    def S_gauss_lorentz_Area(x, center, area, fwhm, fraction):
        sigma = fwhm / (2 * np.sqrt(2 * np.log(2)))
        gamma = fwhm / 2
        height = area / ((1 - fraction / 100) * sigma * np.sqrt(2 * np.pi) + (fraction / 100) * np.pi * gamma)
        return height * (
                (1 - fraction / 100) * PeakFunctions.gaussian(x, center, fwhm, 0) +
                fraction / 100 * PeakFunctions.lorentzian(x, center, fwhm, 100))

