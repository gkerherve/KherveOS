"""Writes public/apps/khervetech/py/shims/matplotlib/cmdata.py: the 256-entry tables of matplotlib's continuous
colour maps, so the recording matplotlib colours images exactly as the desktop does (AFM / TEM / EDX maps).

    python3 tools/make_cmaps.py        # needs matplotlib on the machine that runs it, not in the browser
"""

import base64
from pathlib import Path

import matplotlib
import numpy as np

OUT = Path(__file__).resolve().parent.parent / "public/apps/khervetech/py/shims/matplotlib/cmdata.py"

# the sequential / diverging / cyclic / misc maps; the "_r" ones are reversed at import time
NAMES = [
    "viridis", "plasma", "inferno", "magma", "cividis", "turbo", "twilight", "twilight_shifted", "cubehelix",
    "gray", "bone", "pink", "copper", "hot", "afmhot", "gist_heat", "gist_gray", "gist_yarg", "binary", "spring",
    "summer", "autumn", "winter", "cool", "wistia", "Greys", "Blues", "Greens", "Oranges", "Reds", "Purples",
    "YlOrBr", "YlOrRd", "OrRd", "PuRd", "RdPu", "BuPu", "GnBu", "PuBu", "YlGnBu", "PuBuGn", "BuGn", "YlGn",
    "PiYG", "PRGn", "BrBG", "PuOr", "RdGy", "RdBu", "RdYlBu", "RdYlGn", "Spectral", "coolwarm", "bwr", "seismic",
    "jet", "rainbow", "nipy_spectral", "gist_rainbow", "gist_ncar", "gist_stern", "gist_earth", "terrain", "ocean",
    "cmocean", "hsv", "flag", "prism", "brg", "CMRmap", "gnuplot", "gnuplot2",
]


def main():
    cm = matplotlib.colormaps
    lines = ['"""Generated by tools/make_cmaps.py from matplotlib %s: 256 x RGB (8 bit) per colour map, base64."""\n' % matplotlib.__version__,
             "TABLES = {"]
    kept = 0
    for name in NAMES:
        if name not in cm:
            continue
        lut = (np.asarray(cm[name](np.linspace(0, 1, 256)))[:, :3] * 255 + 0.5).astype(np.uint8)
        lines.append(f"    {name!r}: {base64.b64encode(lut.tobytes()).decode()!r},")
        kept += 1
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{kept} colour maps -> {OUT.relative_to(OUT.parents[6])} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
